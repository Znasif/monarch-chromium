"""Gemini Omni 1.1 Flash (`gemini-omni-1.1-flash`) short video cutaway generator.

Follows `/workspace/ref/skills/gemini-omni-flash-api.md` and `https://ai.google.dev/gemini-api/docs/omni.md.txt`:
  - Uses `client.interactions.create(model="gemini-omni-1.1-flash", ...)`
  - Strictly bounded by Rule 7: at most 3 Omni calls total, and stops calling the paid
    endpoint immediately if a call fails twice (`MAX_FAILURES = 2`), never looping on
    paid calls.
  - No real brands, people, or site screenshots appear in generated prompts.
"""

from __future__ import annotations

import base64
import json
import os
from pathlib import Path
from typing import Dict

ROOT_DIR = Path(__file__).resolve().parent.parent.parent
OMNI_DIR = Path("/tmp/monarch_video_build/omni")
OMNI_STATE_FILE = Path("/tmp/monarch_video_build/omni_budget_state.json")

GEMINI_OMNI_MODEL = "gemini-omni-1.1-flash"
MAX_OMNI_CALLS = 3
MAX_FAILURES = 2

OMNI_PROMPTS: Dict[str, str] = {
    "omni_01_hand_pins": (
        "Continuous, unbroken close-up macro shot on a dark matte desk: a human index fingertip "
        "gently glides left to right across a physical refreshable tactile grid of small raised "
        "ivory-white pins arranged in neat rows. Only sparse one-pin-wide outline contours are "
        "raised while surrounding pins stay flat. Warm studio rim lighting, shallow depth of field. "
        "No logos, no brands, no text on the device, no dialogue."
    ),
    "omni_02_double_press": (
        "Continuous, unbroken overhead studio shot on a dark background: a right index finger "
        "rests on a raised tactile pin contour on a multi-line pin matrix while a left thumb "
        "double-presses a tactile front edge action bar. Immediately after the double-press, "
        "the pin matrix smoothly refreshes to show an enlarged single figure outline. "
        "No logos, no brands, no screens, no dialogue."
    ),
}


def load_omni_state() -> Dict[str, int | bool | str]:
    if OMNI_STATE_FILE.exists():
        try:
            return json.loads(OMNI_STATE_FILE.read_text(encoding="utf-8"))
        except Exception:
            pass
    return {"calls": 0, "failures": 0, "circuit_tripped": False, "last_error": ""}


def save_omni_state(state: Dict[str, int | bool | str]) -> None:
    OMNI_STATE_FILE.parent.mkdir(parents=True, exist_ok=True)
    OMNI_STATE_FILE.write_text(json.dumps(state, indent=2), encoding="utf-8")


def try_generate_omni_clip(clip_id: str) -> Path | None:
    """Attempts to generate a short (<= 8s) 1080p clip via gemini-omni-1.1-flash.

    Respects the 3-call budget and 2-failure circuit breaker (Rule 7).
    Returns the output MP4 path if generated by Gemini Omni, or None if the circuit
    breaker tripped so the caller uses the Manim cutaway renderer.
    """
    OMNI_DIR.mkdir(parents=True, exist_ok=True)
    out_mp4 = OMNI_DIR / f"{clip_id}.mp4"
    if out_mp4.exists() and out_mp4.stat().st_size > 4096:
        return out_mp4

    state = load_omni_state()
    if state.get("circuit_tripped"):
        return None
    if int(state.get("calls", 0)) >= MAX_OMNI_CALLS:
        print(f"[omni] Budget ({MAX_OMNI_CALLS}) reached; skipping paid call for {clip_id}.")
        return None

    prompt = OMNI_PROMPTS[clip_id]
    os.environ["NO_PROXY"] = "localhost,127.0.0.1"
    os.environ["no_proxy"] = "localhost,127.0.0.1"

    state["calls"] = int(state.get("calls", 0)) + 1
    save_omni_state(state)

    try:
        from google import genai

        client = genai.Client()
        interaction = client.interactions.create(
            model=GEMINI_OMNI_MODEL,
            input=prompt,
            response_format={
                "type": "video",
                "resolution": "1080p",
                "aspect_ratio": "16:9",
            },
        )
        video_obj = getattr(interaction, "output_video", None)
        if video_obj and getattr(video_obj, "data", None):
            out_mp4.write_bytes(base64.b64decode(video_obj.data))
            print(f"[omni] Generated {out_mp4.name} via {GEMINI_OMNI_MODEL} (call #{state['calls']}).")
            return out_mp4
        raise RuntimeError("Empty output_video in Gemini Omni response")
    except Exception as exc:
        failures = int(state.get("failures", 0)) + 1
        state["failures"] = failures
        state["last_error"] = str(exc)[:300]
        if failures >= MAX_FAILURES:
            state["circuit_tripped"] = True
            print(
                f"[omni] STOP PAID CALLS: {GEMINI_OMNI_MODEL} failed {failures} times "
                f"(last error: {state['last_error']}). Circuit breaker tripped per Rule 7."
            )
        save_omni_state(state)
        return None
